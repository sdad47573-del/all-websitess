import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('scripts/fetch-maps-photos.mjs', 'utf8');
const m = src.match(/const detailPb = \(fid\) =>\s*\n\s*`([^`]+)`/);
const fid = '0xd6bc3c48c8ce991:0x952dda1f9341e214';
const pb = m[1].replace('${fid}', fid);
const url = `https://www.google.com/maps/preview/place?authuser=0&hl=es&gl=es&pb=${encodeURIComponent(pb)}`;
const r = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/120.0.0.0 Safari/537.36', 'accept-language': 'es-ES,es;q=0.9', cookie: 'CONSENT=YES+cb.20210328-17-p0.en+FX+667;SOCS=CAI' } });
const t = await r.text();
writeFileSync('scripts/tmp-alhambra-preview.txt', t);
console.log('len', t.length, 'starts', JSON.stringify(t.slice(0, 6)));
